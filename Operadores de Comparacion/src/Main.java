public class Main {
    public static void main(String[] args){
        int a = 10, b = 10;

        //comparacion por igualdad
        System.out.println(a == b);
        //comparacion por diferencia
        System.out.println(a != b);
        //comparacion si es mayor
        System.out.println(a > b);
        //comparacion si es mayor o igual
        System.out.println(a >= b);
        //comparacion si es menor
        System.out.println(a < b);
        //comparacion si es menor o igual
        System.out.println(a <= b);
    }
}